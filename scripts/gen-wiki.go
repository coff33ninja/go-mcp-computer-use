//go:build ignore

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type wikiPage struct {
	File    string
	Title   string
	Content string
}

func main() {
	root := "."
	docsDir := filepath.Join(root, "docs")
	metaDir := filepath.Join(docsDir, "meta")
	refDir := filepath.Join(docsDir, "reference")
	guidesDir := filepath.Join(docsDir, "guides")
	wikiDir := filepath.Join(root, "wiki")

	os.MkdirAll(wikiDir, 0755)

	pages := []wikiPage{
		buildHomePage(root, docsDir, metaDir, refDir, guidesDir),
		buildToolsPage(refDir),
		buildArchitecturePage(docsDir),
		buildPlanPage(metaDir),
		buildBacklogPage(metaDir),
		buildChangelogPage(metaDir),
		buildKnownIssuesPage(metaDir),
		buildSecurityPage(root, docsDir),
		buildBuildUsagePage(root),
		buildConfigPage(refDir),
		buildReferenceDocsPage(refDir),
		buildGuidesPage(guidesDir),
		buildCICDPage(docsDir),
	}

	for _, p := range pages {
		path := filepath.Join(wikiDir, p.File)
		header := fmt.Sprintf("<!-- Auto-generated from project docs. Run `go run ./scripts/gen-wiki.go` to regenerate. -->\n\n# %s\n\n", p.Title)
		if p.File != "Home.md" {
			header += "[Home](Home.md) ← "
		}
		full := header + p.Content + "\n\n<!-- Generated by scripts/gen-wiki.go -->\n"
		if err := os.WriteFile(path, []byte(full), 0644); err != nil {
			fmt.Fprintf(os.Stderr, "error writing %s: %v\n", path, err)
			os.Exit(1)
		}
		fmt.Printf("wrote %s\n", path)
	}
	fmt.Printf("wiki: %d pages in %s\n", len(pages), wikiDir)
}

