func buildChangelogPage(metaDir string) wikiPage {
	var b strings.Builder
	data, err := os.ReadFile(filepath.Join(metaDir, "CHANGELOG.md"))
	if err != nil {
		b.WriteString("_Changelog not found._\n")
	} else {
		versionHeadings := 0
		for _, line := range strings.Split(string(data), "\n") {
			if strings.HasPrefix(line, "## [") {
				versionHeadings++
			}
			if versionHeadings <= 10 {
				b.WriteString(line + "\n")
			} else {
				b.WriteString("\n_... older versions omitted._\n")
				break
			}
		}
	}
	return wikiPage{File: "Changelog.md", Title: "Changelog", Content: b.String()}
}

